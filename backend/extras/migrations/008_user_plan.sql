-- 008: тариф пользователя и лимиты генерации
--
-- До этого момента PRO был чистой заглушкой (см. src/lib/plans.js,
-- PRO_LAUNCHED = false) — ни колонки, ни лимитов не существовало, всё было
-- безлимитно для всех. Теперь тариф реальный: free — 15 генераций в месяц,
-- pro — 150. Оплата не автоматизирована (нет подключённого платёжного
-- провайдера) — plan переключается вручную через admin-панель
-- (см. admin/README.md) после того, как учитель оплатил вне сайта.
--
-- Лимит считается не отдельным счётчиком, а прямым COUNT(*) по таблице
-- generations (status = 'done', created_at в текущем календарном месяце) —
-- см. backend/src/Plans.php. Отдельная таблица-счётчик была бы лишним
-- дублированием источника истины и требовала бы синхронизации при откате
-- неудачных генераций.

ALTER TABLE users
  ADD COLUMN IF NOT EXISTS plan VARCHAR(10) NOT NULL DEFAULT 'free';

ALTER TABLE users
  ADD CONSTRAINT users_plan_check CHECK (plan IN ('free', 'pro'));
